<?php

declare(strict_types=1);

use Dakotajune\Seeders\Support\DraftException;
use Dakotajune\Seeders\Support\Report;

const DRAFT = <<<'YAML'
models:
  Category:
    name: string:60 unique
  Product:
    name: string
    category_id: id

seeders:
  reference:
    Category:
      rows: [Books, Games]
  demo:
    Product: 3
YAML;

function build(string $yaml = DRAFT, array $only = ['factories', 'seeders']): array
{
    $blueprint = blueprint();

    return $blueprint->generate($blueprint->analyze($blueprint->parse($yaml)), $only);
}

it('writes the factories and seeders of a draft through Blueprint itself', function () {
    inProject(function () {
        $out = build();

        expect(array_keys($out))->toBe(['created'])
            ->and(paths($out['created']))->toContain(
                'database/factories/CategoryFactory.php',
                'database/factories/ProductFactory.php',
                'database/seeders/Reference/CategorySeeder.php',
                'database/seeders/Demo/ProductSeeder.php',
                'database/seeders/DatabaseSeeder.php',
            )
            ->and(file_exists('database/factories/ProductFactory.php'))->toBeTrue();
    });
});

it('puts a header on what it writes, and still writes PHP that parses', function () {
    inProject(function () {
        build();
        $source = file_get_contents('database/factories/ProductFactory.php');

        expect($source)->toContain('// @generated by dakotajune/seeders [hash:')
            ->and(lints($source))->toBeTrue();
    });
});

it('uses its own lexer for seeders: and not Blueprint\'s, which cannot read a map', function () {
    inProject(function () {
        // Blueprint's SeederLexer would hand this array to preg_split() and fail.
        expect(fn () => build())->not->toThrow(Throwable::class);
    });
});

it('writes with the line ending of the machine, nothing mixed', function () {
    inProject(function () {
        build();
        $source = file_get_contents('database/factories/ProductFactory.php');

        expect(str_replace(PHP_EOL, '', $source))->not->toContain("\n")->not->toContain("\r");
    });
});

it('overwrites a hand-edited factory by default, as Blueprint does', function () {
    inProject(function () {
        build();
        file_put_contents('database/factories/ProductFactory.php', "<?php // mine\n");
        $out = build();

        expect(file_get_contents('database/factories/ProductFactory.php'))->not->toContain('mine')
            ->and($out)->not->toHaveKey('skipped');
    });
});

it('leaves a hand-edited file alone under protect, says so, and lists it as skipped', function () {
    inProject(function () {
        build();
        $path = 'database/factories/ProductFactory.php';
        file_put_contents($path, file_get_contents($path) . "\n// my change\n");
        $out = build();

        expect(file_get_contents($path))->toContain('my change')
            ->and($out['skipped'])->toBe([entry('Factory', $path)])
            ->and(Report::drain())->toContain($path . ': not written: it was edited by hand since it was generated (seeders.overwrite is protect).');
    }, ['seeders.overwrite' => 'protect']);
});

it('regenerates an untouched file under protect, whatever the line endings on disk', function () {
    inProject(function () {
        build();
        $path = 'database/factories/ProductFactory.php';
        file_put_contents($path, str_replace("\n", "\r\n", str_replace("\r\n", "\n", file_get_contents($path))));
        $out = build();

        expect($out)->not->toHaveKey('skipped');
    }, ['seeders.overwrite' => 'protect']);
});

it('writes nothing in a dry run, and says so', function () {
    inProject(function () {
        $out = build();

        expect(file_exists('database/factories/ProductFactory.php'))->toBeFalse()
            ->and($out['created'])->not->toBeEmpty()
            ->and(implode(' ', Report::drain()))->toContain('dry run');
    }, ['seeders.dry_run' => true]);
});

it('stops with the model and column when the draft cannot be generated', function () {
    inProject(function () {
        $yaml = "models:\n  Node:\n    parent_id: id:node\n";

        expect(fn () => build($yaml))->toThrow(DraftException::class, 'Node.parent_id');
    });
});

it('tells the author what it could not do, after the build', function () {
    inProject(function () {
        build("models:\n  Place:\n    area: point\n", ['factories']);

        expect(Report::drain()[0])->toStartWith('Place.area');
    });
});

it('leaves a DatabaseSeeder of the project\'s own alone and prints the lines to add', function () {
    inProject(function () {
        mkdir('database/seeders', 0777, true);
        file_put_contents('database/seeders/DatabaseSeeder.php', "<?php\n\nnamespace Database\\Seeders;\n\nuse Illuminate\\Database\\Seeder;\n\nclass DatabaseSeeder extends Seeder\n{\n    public function run(): void\n    {\n        \$this->call(UserSeeder::class);\n    }\n}\n");
        $out = build();
        $notes = implode("\n", Report::drain());

        expect(file_get_contents('database/seeders/DatabaseSeeder.php'))->toContain('UserSeeder')->not->toContain('@generated')
            ->and($out['skipped'])->toBe([entry('Seeder', 'database/seeders/DatabaseSeeder.php')])
            ->and($notes)->toContain('$this->call(ReferenceSeeder::class);')->toContain('DemoSeeder::class');
    });
});

it('replaces the DatabaseSeeder Laravel ships', function () {
    inProject(function () {
        mkdir('database/seeders', 0777, true);
        file_put_contents('database/seeders/DatabaseSeeder.php', "<?php\n\nnamespace Database\\Seeders;\n\nuse Illuminate\\Database\\Seeder;\n\nclass DatabaseSeeder extends Seeder\n{\n    public function run(): void\n    {\n    }\n}\n");
        build();

        expect(file_get_contents('database/seeders/DatabaseSeeder.php'))->toContain('ReferenceSeeder');
    });
});

it('does not run for a draft with nothing to seed, or when only factories are asked for', function () {
    inProject(function () {
        $out = build("models:\n  Post:\n    title: string\n", ['seeders']);

        expect($out)->toBe([]);

        build(only: ['factories']);

        expect(file_exists('database/seeders/DatabaseSeeder.php'))->toBeFalse();
    });
});

it('catches a Faker method that does not exist, naming the column and the nearest real one', function () {
    inProject(function () {
        $yaml = "models:\n  Person:\n    email_address: string fake:emial\n";

        expect(fn () => build($yaml, ['factories']))->toThrow(DraftException::class, 'Person.email_address')
            ->and(fn () => build($yaml, ['factories']))->toThrow(DraftException::class, 'email');
    });
});
