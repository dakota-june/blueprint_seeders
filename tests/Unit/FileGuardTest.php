<?php

declare(strict_types=1);

use Dakotajune\Seeders\Support\Eol;
use Dakotajune\Seeders\Support\FileGuard;
use Dakotajune\Seeders\Support\StockDatabaseSeeder;
use Illuminate\Filesystem\Filesystem;

function scratch(): string
{
    $dir = sys_get_temp_dir() . '/seeders-guard-' . bin2hex(random_bytes(4));
    mkdir($dir, 0777, true);

    return $dir;
}

function guard(string $policy = 'always', bool $dry = false): FileGuard
{
    return new FileGuard(new Filesystem(), $policy, $dry);
}

const GUARD_SOURCE = "<?php\n\nclass A\n{\n}\n";

it('stamps the file with a header and a hash that survive a change of line ending', function () {
    $stamped = FileGuard::stamp(GUARD_SOURCE);

    expect($stamped)->toStartWith("<?php\n// @generated by dakotajune/seeders [hash:")
        ->and(FileGuard::unstamp(Eol::to($stamped, "\r\n"))[0])->toBe(Eol::hash(GUARD_SOURCE))
        ->and(Eol::lf(FileGuard::unstamp($stamped)[1]))->toBe(GUARD_SOURCE);
});

it('creates a file that is not there, then finds it unchanged', function () {
    $path = scratch() . '/sub/A.php';

    $first = guard()->write($path, GUARD_SOURCE);
    $second = guard()->write($path, GUARD_SOURCE);

    expect($first->action)->toBe('created')->and(is_file($path))->toBeTrue()
        ->and($second->action)->toBe('unchanged');
});

it('regenerates what it wrote, and reports it as updated', function () {
    $path = scratch() . '/A.php';
    guard()->write($path, GUARD_SOURCE);

    $decision = guard()->write($path, "<?php\n\nclass B\n{\n}\n");

    expect($decision->action)->toBe('updated')->and(file_get_contents($path))->toContain('class B');
});

it('overwrites a hand-edited file under always, which is Blueprint\'s own way', function () {
    $path = scratch() . '/A.php';
    guard()->write($path, GUARD_SOURCE);
    file_put_contents($path, file_get_contents($path) . "// mine\n");

    expect(guard('always')->write($path, GUARD_SOURCE)->action)->toBe('updated')
        ->and(file_get_contents($path))->not->toContain('// mine');
});

it('skips a hand-edited file under protect and says why', function () {
    $path = scratch() . '/A.php';
    guard()->write($path, GUARD_SOURCE);
    file_put_contents($path, file_get_contents($path) . "// mine\n");

    $decision = guard('protect')->write($path, "<?php\n\nclass B\n{\n}\n");

    expect($decision->action)->toBe('skipped')->and($decision->reason)->toContain('edited by hand')
        ->and(file_get_contents($path))->toContain('// mine')->not->toContain('class B');
});

it('regenerates an untouched file under protect', function () {
    $path = scratch() . '/A.php';
    guard()->write($path, GUARD_SOURCE);

    expect(guard('protect')->write($path, "<?php\n\nclass B\n{\n}\n")->action)->toBe('updated');
});

it('treats a file without the header as not generated here', function () {
    $path = scratch() . '/A.php';
    file_put_contents($path, GUARD_SOURCE);

    $decision = guard('protect')->write($path, "<?php\n\nclass B\n{\n}\n");

    expect($decision->action)->toBe('skipped')->and($decision->reason)->toContain('not generated');
});

it('only creates under never', function () {
    $path = scratch() . '/A.php';

    expect(guard('never')->write($path, GUARD_SOURCE)->action)->toBe('created')
        ->and(guard('never')->write($path, "<?php\n\nclass B\n{\n}\n")->action)->toBe('skipped');
});

it('writes nothing in a dry run, and still says what it would do', function () {
    $path = scratch() . '/A.php';

    $decision = guard('always', dry: true)->write($path, GUARD_SOURCE);

    expect($decision->action)->toBe('created')->and(is_file($path))->toBeFalse()
        ->and($decision->new)->toContain('class A');
});

it('keeps the old and new text on the decision, for a diff', function () {
    $path = scratch() . '/A.php';
    guard()->write($path, GUARD_SOURCE);

    $decision = guard('always', dry: true)->write($path, "<?php\n\nclass B\n{\n}\n");

    expect($decision->old)->toContain('class A')->and($decision->new)->toContain('class B');
});

it('leaves a hand-written file alone even under always when it is marked as one that matters', function () {
    $path = scratch() . '/DatabaseSeeder.php';
    file_put_contents($path, "<?php\n\nclass DatabaseSeeder\n{\n    public function run(): void { Thing::seed(); }\n}\n");

    $decision = guard('always')->write($path, GUARD_SOURCE, guardHandWritten: true);

    expect($decision->action)->toBe('skipped')->and($decision->reason)->toContain('hand-written');
});

it('recognises the DatabaseSeeder Laravel ships, in the versions that differ', function (string $source) {
    expect(StockDatabaseSeeder::matches($source))->toBeTrue();
})->with([
    'laravel 11 and 12' => ["<?php\n\nnamespace Database\\Seeders;\n\nuse App\\Models\\User;\n// use Illuminate\\Database\\Console\\Seeds\\WithoutModelEvents;\nuse Illuminate\\Database\\Seeder;\n\nclass DatabaseSeeder extends Seeder\n{\n    /**\n     * Seed the application's database.\n     */\n    public function run(): void\n    {\n        // User::factory(10)->create();\n\n        User::factory()->create([\n            'name' => 'Test User',\n            'email' => 'test@example.com',\n        ]);\n    }\n}\n"],
    'laravel 10' => ["<?php\n\nnamespace Database\\Seeders;\n\n// use Illuminate\\Database\\Console\\Seeds\\WithoutModelEvents;\nuse Illuminate\\Database\\Seeder;\n\nclass DatabaseSeeder extends Seeder\n{\n    public function run(): void\n    {\n        // \\App\\Models\\User::factory(10)->create();\n\n        // \\App\\Models\\User::factory()->create([\n        //     'name' => 'Test User',\n        //     'email' => 'test@example.com',\n        // ]);\n    }\n}\n"],
    'with the trait' => ["<?php\n\nnamespace Database\\Seeders;\n\nuse App\\Models\\User;\nuse Illuminate\\Database\\Console\\Seeds\\WithoutModelEvents;\nuse Illuminate\\Database\\Seeder;\n\nclass DatabaseSeeder extends Seeder\n{\n    use WithoutModelEvents;\n\n    public function run(): void\n    {\n        User::factory()->create([\n            'name' => 'Test User',\n            'email' => 'test@example.com',\n        ]);\n    }\n}\n"],
]);

it('does not mistake a seeder with real work in it for the stock one', function () {
    $source = "<?php\n\nnamespace Database\\Seeders;\n\nuse Illuminate\\Database\\Seeder;\n\nclass DatabaseSeeder extends Seeder\n{\n    public function run(): void\n    {\n        \$this->call(RoleSeeder::class);\n    }\n}\n";

    expect(StockDatabaseSeeder::matches($source))->toBeFalse();
});
